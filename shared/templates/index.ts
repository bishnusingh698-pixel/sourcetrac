const BY_ID = new Map(TEMPLATES.map((t) => [t.id, t]));

export function templateById(id: string): TemplateDefinition | undefined {
  return BY_ID.get(id);
}

/** Templates in one category, in declaration order. */
export function templatesByCategory(category: TemplateCategory): TemplateDefinition[] {
  return TEMPLATES.filter((t) => t.category === category);
}

/** The Lite version's question keys, as a set. */
export function liteQuestionKeys(template: TemplateDefinition): Set<string> {
  return new Set(template.liteQuestionKeys);
}
