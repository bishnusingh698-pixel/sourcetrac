/**
 * The 21 outcome-first templates.
 *
 * All copy lives in `shared/templates/locales/<locale>.json`, keyed by template
 * id and field. This module holds structure only: stable ids, question types,
 * which questions are required/optional, show-if logic, defaults, tags, ideas
 * and smart actions.
 *
 * Option keys are stable and intentional (they feed tags and results), so a
 * template's option `key`s must never be renamed.
 */

import type { TemplateCategory, TemplateDefinition, TemplateOption, TemplateQuestion } from "./types";

/** A fixed option. `labelKey` defaults to the template's own namespace. */
function opt(key: string, labelKey: string): TemplateOption {
  return { key, labelKey };
}

/** Pack-based option set (labels come from `packs.ts`). */
function packQuestion(
  key: string,
  textKey: string,
  extra: Partial<TemplateQuestion> = {},
): TemplateQuestion {
  return {
    key,
    type: "single_choice",
    textKey,
    required: true,
    ...extra,
  };
}

